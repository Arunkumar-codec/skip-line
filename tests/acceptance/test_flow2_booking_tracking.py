import pytest
from playwright.async_api import expect

from tests.acceptance.conftest import ui_login

pytestmark = pytest.mark.asyncio


async def test_flow2_book_track_and_track_owner_isolation(page, server):
    await ui_login(page, "user", server.user1_email, server.user_password)

    # Search organisations and open the real booking modal
    await page.goto(
        "/user/organizations?q=" + server.org_name.split()[0],
        wait_until="domcontentloaded")
    await page.click('[onclick*="openBookModal"]')
    await expect(page.locator("#bookModal")).to_be_visible()

    # Pick the seeded service and counter through the rendered selects
    await page.select_option("#bookServiceId", str(server.service_id))
    await page.select_option("#bookCounterId", str(server.counter_id))
    await page.click("#confirmBookBtn")

    # Confirmation panel shows the issued token
    await expect(page.locator("#bookStep2")).to_be_visible()
    token_number = await page.locator("#bookedTokenNum").inner_text()
    assert token_number and token_number.strip() not in ("", "-")
    track_href = await page.locator("#trackLink").get_attribute("href")
    receipt_href = await page.locator("#receiptLinkBook").get_attribute("href")
    token_id = int(track_href.rsplit("/", 1)[-1])

    # Database verification: token exists, waiting, owned by user 1
    token = server.db_fetchone(
        "SELECT id, token_number, status, user_id, organization_id, "
        "counter_id, service_id, queue_position FROM tokens WHERE id = :t",
        {"t": token_id})
    assert token[1] == token_number.strip()
    assert token[2] == "WAITING"
    assert token[3] == server.user1_id
    assert token[4] == server.org_id and token[5] == server.counter_id
    assert token[6] == server.service_id
    assert token[7] == 1, token

    # Tracking page (real navigation, real render)
    await page.click("#trackLink")
    await page.wait_for_url("**/track/**", timeout=20000)
    await expect(page.locator("#tokenNum")).to_have_text(token_number.strip())
    await expect(page.locator("#tokenStatus")).to_contain_text(
        "waiting", ignore_case=True)

    # Receipt (owner opens it). The receipt is a rendered PDF document
    # (QR-001 FileResponse, application/pdf): navigating to it starts a
    # DOWNLOAD (Playwright raises "Download is starting" on page.goto),
    # and a PDF does not expose token text to page.content() anyway. The
    # owner check therefore verifies the real HTTP contract over the
    # page's own request context (which carries the owner session
    # cookies): 200 + PDF content type.
    rec = await page.context.request.get(receipt_href)
    assert rec.status == 200, rec.status
    assert rec.headers.get("content-type", "").startswith("application/pdf")

    # ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ Boundary: a DIFFERENT customer cannot see the private booking ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬
    page2 = await page.context.browser.new_context(
        base_url=server.base_url, viewport={"width": 1280, "height": 900})
    p2 = await page2.new_page()
    await ui_login(p2, "user", server.user2_email, server.user_password)

    await p2.goto(f"/user/track/{token_id}", wait_until="domcontentloaded")
    assert "Token not found" in (await p2.content())
    assert token_number.strip() not in (await p2.content())

    # Cross-user receipt: the SAME PDF-navigation constraint applies, so
    # fetch over user 2's request context and expect the uniform 404
    # (QR-001 deny contract).
    other = await p2.context.request.get(receipt_href)
    assert other.status == 404
    await page2.close()
