import pytest
from playwright.async_api import expect

from tests.acceptance.conftest import api_login_cookie, ui_login

pytestmark = pytest.mark.asyncio


async def test_flow5_manual_book_then_ai_continuity_confirm_gating(page, server):
    await ui_login(page, "user", server.user1_email, server.user_password)

    baseline_tokens = server.db_count("tokens", "1=1")

    # Prepare an AI-ready manual context: open the booking modal, select the
    # service, then take the AI hand-off link from the modal footer.
    await page.goto(
        "/user/organizations?q=" + server.org_name.split()[0],
        wait_until="domcontentloaded")
    await page.click('[onclick*="openBookModal"]')
    await expect(page.locator("#bookModal")).to_be_visible()
    await page.select_option("#bookServiceId", str(server.service_id))
    await page.click("#continueWithAi")
    await page.wait_for_url("**/assistant**", timeout=20000)
    await expect(page.locator("#chatLog")).to_be_visible()
    # startSession automatically created the conversation (mock provider
    # answers the first turn deterministically).
    await expect(page.locator("#chatLog > div").last).not_to_be_empty(
        timeout=20000)

    # Drive the mock provider through the real tools with a deterministic
    # directive: search org ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚Â ÃƒÂ¢Ã¢â€šÂ¬Ã¢â€žÂ¢ list services ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚Â ÃƒÂ¢Ã¢â€šÂ¬Ã¢â€žÂ¢ counters ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚Â ÃƒÂ¢Ã¢â€šÂ¬Ã¢â€žÂ¢ quote ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚Â ÃƒÂ¢Ã¢â€šÂ¬Ã¢â€žÂ¢ draft.
    service_directive = (
        f'Please book me: org="{server.org_name}" service="{server.service_name}"')
    await page.fill("#chatInput", service_directive)
    await page.press("#chatInput", "Enter")

    # The draft (real backend data) arrives ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚Â ÃƒÂ¢Ã¢â€šÂ¬Ã¢â€žÂ¢ confirm bar appears
    await expect(page.locator("#confirmBar")).to_be_visible(timeout=30000)
    draft_text = await page.locator("#draftBody").inner_text()
    assert server.org_name in draft_text
    assert server.service_name in draft_text
    assert "49.00" in draft_text  # exactly the seeded service price
    assert '"slot_id": null' in draft_text or '"slot_id":null' in draft_text.replace(
        " ", ""), draft_text

    # NO booking exists until the customer explicitly confirms.
    tokens_pre_confirm = server.db_count("tokens", "1=1")
    assert tokens_pre_confirm == baseline_tokens

    # Explicit confirmation through the app control
    await page.click("#confirmBar button.btn-success")
    await expect(page.get_by_text("Booking confirmed")).to_be_visible(
        timeout=30000)

    tokens_booked = server.db_count("tokens", "1=1")
    assert tokens_booked == baseline_tokens + 1

    # The booked draft must reference the real seeded org/service
    book_row = server.db_fetchone(
        "SELECT organization_id, service_id, user_id, status FROM tokens "
        "ORDER BY id DESC LIMIT 1")
    assert book_row[0] == server.org_id and book_row[1] == server.service_id
    assert book_row[2] == server.user1_id and book_row[3] == "WAITING"

    # Repeat-confirm (no duplicate booking): conversation-keyed idempotency
    conv_state = await page.evaluate("async () => (await fetch(`/ai/conversations/${convId}`)).json()")
    conversation_id = conv_state["data"]["id"]
    repeat = await page.evaluate(
        "async () => (await fetch(`/ai/conversations/${convId}/book`, "
        "{method: 'POST'})).json()")
    assert repeat.get("data", {}).get("booked") in (True, False)
    tokens_after_repeat = server.db_count("tokens", "1=1")
    assert tokens_after_repeat == tokens_booked, tokens_after_repeat

    # ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ ownership isolation: user 2 gets a uniform 404 for this conversation
    cookies2 = await api_login_cookie(
        server.base_url, "user", server.user2_email, server.user_password)
    isolation = await page.evaluate(
        """async (cid) => {
            const res = await fetch(`/ai/conversations/${cid}`, {method: 'GET'});
            return res.status;
        }""",
        conversation_id,
    )
    # NOTE: the browser session belongs to user 1, so cross-user isolation
    # is asserted over HTTPX with user 2's own session cookies.
    import httpx
    async with httpx.AsyncClient(
            base_url=server.base_url, cookies=cookies2) as hc:
        r = await hc.get(f"/ai/conversations/{conversation_id}")
    assert r.status_code == 404, r.text
    assert isolation == 200  # (sanity: the owner browser still reads it)
