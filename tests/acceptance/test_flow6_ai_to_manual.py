import pytest
from playwright.async_api import expect

from tests.acceptance.conftest import ui_login

pytestmark = pytest.mark.asyncio


async def test_flow6_ai_draft_toolverifying_context_and_manual_completion(
        page, server):
    await ui_login(page, "user", server.user1_email, server.user_password)

    baseline_tokens = server.db_count("tokens", "1=1")

    await page.goto("/user/assistant", wait_until="domcontentloaded")
    await expect(page.locator("#chatLog")).to_be_visible()

    # Start an AI conversation and surface the validated draft using the
    # strict mock directive (ids/price come only from real TOOL_RESULT data).
    await page.fill(
        "#chatInput",
        f'Book me: org="{server.org_name}" service="{server.service_name}"')
    await page.press("#chatInput", "Enter")

    await expect(page.locator("#confirmBar")).to_be_visible(timeout=30000)
    draft_text = await page.locator("#draftBody").inner_text()
    assert server.counter_name in draft_text
    assert "49.00" in draft_text

    # ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ switch to MANUAL mode; prefill carries the REAL draft values ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬
    await page.click('button:has-text("Switch to Manual")')
    await expect(page.locator("#manualPrefill")).to_be_visible(timeout=20000)
    prefill = await page.locator("#manualPrefill").inner_text()
    assert server.org_name in prefill
    assert server.service_name in prefill

    # Conversation still owns its draft (nothing lost on the switch).
    # convId is a JS global on /user/assistant; capture the id Python-side
    # here so later checks work even after navigating away from the chat.
    state = await page.evaluate(
        "async () => (await fetch(`/ai/conversations/${convId}`)).json()")
    assert state.get("data", {}).get("mode") == "manual", state
    assert state.get("data", {}).get("draft"), state
    conversation_id = state["data"]["id"]

    # ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ complete the booking MANUALLY through the booking modal ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬
    await page.goto(
        "/user/organizations?q=" + server.org_name.split()[0],
        wait_until="domcontentloaded")
    await page.click('[onclick*="openBookModal"]')
    await expect(page.locator("#bookModal")).to_be_visible()
    await page.select_option("#bookServiceId", str(server.service_id))
    await page.select_option("#bookCounterId", str(server.counter_id))
    await page.click("#confirmBookBtn")
    await expect(page.locator("#bookStep2")).to_be_visible()
    token_number = (await page.locator("#bookedTokenNum").inner_text()).strip()
    track_href = await page.locator("#trackLink").get_attribute("href")
    token_id = int(track_href.rsplit("/", 1)[-1])

    # Exactly one NEW token was created; it belongs to the right org/service
    tokens_after = server.db_count("tokens", "1=1")
    assert tokens_after == baseline_tokens + 1
    row = server.db_fetchone(
        "SELECT token_number, organization_id, service_id, counter_id, "
        "status, user_id FROM tokens WHERE id = :t", {"t": token_id})
    assert row[0] == token_number
    assert (row[1], row[2], row[3]) == (
        server.org_id, server.service_id, server.counter_id)
    assert row[4] == "WAITING" and row[5] == server.user1_id

    # The manual booking and the AI draft refer to the SAME context
    final_state = await page.evaluate(
        "async (cid) => (await fetch(`/ai/conversations/${cid}`)).json()",
        conversation_id)
    draft = final_state.get("data", {}).get("draft") or {}
    assert draft.get("organization_id") == server.org_id
    assert draft.get("service_id") == server.service_id
    assert draft.get("counter_id") == server.counter_id

    # Tracking page shows the finished manual booking
    await page.goto(f"/user/track/{token_id}", wait_until="domcontentloaded")
    await expect(page.locator("#tokenNum")).to_have_text(token_number)
    await expect(page.locator("#tokenStatus")).to_contain_text(
        "waiting", ignore_case=True)

    # ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ ownership isolation (other customer gets uniform 404) ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚ÂÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬
    await page.goto("/user/logout")
    await ui_login(page, "user", server.user2_email, server.user_password)
    conv_id = final_state["data"]["id"]
    status = await page.evaluate(
        "async (cid) => (await fetch(`/ai/conversations/${cid}`)).status",
        conv_id)
    assert status == 404, status
