"""
models/support.py
────────────────
Phase 7 — Unified Support Cases & Tickets (SUP-001..007, CASE-001..004).

One case domain for USER_TO_ORG / USER_TO_ADMIN / ORG_TO_ADMIN /
ORG_REPORT_USER / PAYMENT_DISPUTE / FEEDBACK_REPORT / OTHER, bound
server-side to validated entities (CASE-002). Case references are stable
readable ids generated by the service; snapshot columns keep historical
cases intact when parties are later deleted/suspended (CASE-003).
Attachments are private: they are only stored, never statically mounted,
and every download passes a participant-authorized endpoint that appends
an audit event (CASE-004).
"""

import enum

from sqlalchemy import JSON, DateTime, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base
from models.mixins import TimestampMixin


class CaseType:
    USER_TO_ORG = "user_to_org"
    USER_TO_ADMIN = "user_to_admin"
    ORG_TO_ADMIN = "org_to_admin"
    ORG_REPORT_USER = "org_report_user"
    PAYMENT_DISPUTE = "payment_dispute"
    FEEDBACK_REPORT = "feedback_report"
    OTHER = "other"

    ALL = {
        USER_TO_ORG, USER_TO_ADMIN, ORG_TO_ADMIN, ORG_REPORT_USER,
        PAYMENT_DISPUTE, FEEDBACK_REPORT, OTHER,
    }


class CaseStatus:
    SUBMITTED = "submitted"
    ACKNOWLEDGED = "acknowledged"
    ASSIGNED = "assigned"
    IN_REVIEW = "in_review"
    WAITING_FOR_PARTY = "waiting_for_party"
    SOLUTION_PROPOSED = "solution_proposed"
    RESOLVED = "resolved"
    CLOSED = "closed"
    REOPENED = "reopened"
    ESCALATED = "escalated"

    # SUP-004 legal transition graph (validated server-side).
    TRANSITIONS = {
        SUBMITTED: {ACKNOWLEDGED, ASSIGNED, IN_REVIEW, SOLUTION_PROPOSED,
                    ESCALATED, CLOSED},
        ACKNOWLEDGED: {ASSIGNED, IN_REVIEW, SOLUTION_PROPOSED, ESCALATED, CLOSED},
        ASSIGNED: {IN_REVIEW, WAITING_FOR_PARTY, SOLUTION_PROPOSED, ESCALATED, CLOSED},
        IN_REVIEW: {WAITING_FOR_PARTY, SOLUTION_PROPOSED, RESOLVED, ESCALATED, CLOSED},
        WAITING_FOR_PARTY: {IN_REVIEW, SOLUTION_PROPOSED, ESCALATED, CLOSED},
        SOLUTION_PROPOSED: {RESOLVED, IN_REVIEW, WAITING_FOR_PARTY, ESCALATED, CLOSED},
        RESOLVED: {CLOSED, REOPENED},
        REOPENED: {IN_REVIEW, WAITING_FOR_PARTY, SOLUTION_PROPOSED, ESCALATED, CLOSED},
        ESCALATED: {ASSIGNED, IN_REVIEW, WAITING_FOR_PARTY, SOLUTION_PROPOSED, CLOSED},
        CLOSED: {REOPENED},
    }


class MessageVisibility:
    PARTIES = "parties"      # visible to all authorized participants
    INTERNAL = "internal"    # admin-only note, never exposed to other parties


class MessageReviewStatus:
    SENT = "sent"
    PENDING_REVIEW = "pending_review"    # sensitive suggested solution awaits
    APPROVED = "approved"


class SupportCase(Base, TimestampMixin):
    __tablename__ = "support_cases"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    # Stable human-readable reference (CASE-001), e.g. "SC-20261101-8f3a".
    reference: Mapped[str] = mapped_column(String(24), nullable=False, unique=True, index=True)

    case_type: Mapped[str] = mapped_column(String(30), nullable=False, index=True)
    category: Mapped[str] = mapped_column(String(40), nullable=False)
    status: Mapped[str] = mapped_column(String(30), nullable=False, default=CaseStatus.SUBMITTED, index=True)

    subject: Mapped[str] = mapped_column(String(200), nullable=False)
    detail: Mapped[str] = mapped_column(Text, nullable=False)

    # Bindings (CASE-001). Every FK is validated server-side on creation.
    user_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True, index=True
    )
    organization_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("organizations.id", ondelete="SET NULL"), nullable=True, index=True
    )
    branch_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("branches.id", ondelete="SET NULL"), nullable=True, index=True
    )
    employee_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("employees.id", ondelete="SET NULL"), nullable=True
    )
    counter_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("counters.id", ondelete="SET NULL"), nullable=True
    )
    service_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("services.id", ondelete="SET NULL"), nullable=True
    )
    token_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("tokens.id", ondelete="SET NULL"), nullable=True, index=True
    )
    payment_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("payments.id", ondelete="SET NULL"), nullable=True, index=True
    )
    feedback_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("feedback.id", ondelete="SET NULL"), nullable=True, index=True
    )
    parent_case_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("support_cases.id", ondelete="SET NULL"), nullable=True
    )

    # CASE-003 suspension-safe snapshots (JSON): display names/values
    # frozen at creation so history survives later deletion/suspension.
    snapshot: Mapped[dict | None] = mapped_column(JSON, nullable=True)

    assigned_admin_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("admins.id", ondelete="SET NULL"), nullable=True
    )
    resolution_note: Mapped[str | None] = mapped_column(Text, nullable=True)
    resolution_accepted_by: Mapped[str | None] = mapped_column(String(20), nullable=True)
    resolved_at: Mapped[DateTime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    closed_at: Mapped[DateTime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    reopened_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)

    created_by_type: Mapped[str | None] = mapped_column(String(20), nullable=True)
    created_by_id: Mapped[int | None] = mapped_column(Integer, nullable=True)

    participants: Mapped[list["CaseParticipant"]] = relationship(
        "CaseParticipant", back_populates="case", cascade="all, delete-orphan",
    )
    messages: Mapped[list["CaseMessage"]] = relationship(
        "CaseMessage", back_populates="case", cascade="all, delete-orphan",
        order_by="CaseMessage.id",
    )
    attachments: Mapped[list["CaseAttachment"]] = relationship(
        "CaseAttachment", back_populates="case", cascade="all, delete-orphan",
    )

    def __repr__(self) -> str:
        return f"<SupportCase {self.reference} {self.status}>"


class CaseParticipant(Base):
    __tablename__ = "case_participants"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    case_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("support_cases.id", ondelete="CASCADE"),
        nullable=False, index=True,
    )
    participant_type: Mapped[str] = mapped_column(String(20), nullable=False)  # user|organization|admin
    participant_id: Mapped[int | None] = mapped_column(Integer, nullable=True)
    display_name: Mapped[str] = mapped_column(String(200), nullable=False)
    role: Mapped[str] = mapped_column(String(20), nullable=False)  # reporter|respondent|admin
    joined_at: Mapped["DateTime | None"] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    # SUP-005 read state (used by the unread-count APIs).
    last_read_at: Mapped["DateTime | None"] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    case: Mapped["SupportCase"] = relationship("SupportCase", back_populates="participants")

    def __repr__(self) -> str:
        return f"<CaseParticipant case={self.case_id} {self.participant_type}#{self.participant_id}>"


class CaseMessage(Base, TimestampMixin):
    __tablename__ = "case_messages"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    case_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("support_cases.id", ondelete="CASCADE"),
        nullable=False, index=True,
    )
    sender_type: Mapped[str] = mapped_column(String(20), nullable=False)
    sender_id: Mapped[int | None] = mapped_column(Integer, nullable=True)
    sender_name: Mapped[str] = mapped_column(String(200), nullable=False)  # snapshot
    body: Mapped[str] = mapped_column(Text, nullable=False)
    visibility: Mapped[str] = mapped_column(String(20), nullable=False, default=MessageVisibility.PARTIES)
    # KB-002: a suggested solution taken from a SENSITIVE knowledge item is
    # a draft awaiting explicit human approval before parties can read it.
    review_status: Mapped[str] = mapped_column(
        String(20), nullable=False, default=MessageReviewStatus.SENT
    )
    suggested_solution_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("knowledge_solutions.id", ondelete="SET NULL"), nullable=True
    )

    case: Mapped["SupportCase"] = relationship("SupportCase", back_populates="messages")

    def __repr__(self) -> str:
        return f"<CaseMessage id={self.id} case={self.case_id} {self.sender_type}>"


class CaseAttachment(Base, TimestampMixin):
    __tablename__ = "case_attachments"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    case_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("support_cases.id", ondelete="CASCADE"),
        nullable=False, index=True,
    )
    message_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("case_messages.id", ondelete="SET NULL"), nullable=True
    )
    uploaded_by_type: Mapped[str | None] = mapped_column(String(20), nullable=True)
    uploaded_by_id: Mapped[int | None] = mapped_column(Integer, nullable=True)
    filename: Mapped[str] = mapped_column(String(255), nullable=False)   # ORIGINAL name
    stored_path: Mapped[str] = mapped_column(String(500), nullable=False)  # unguessable path
    mime: Mapped[str | None] = mapped_column(String(100), nullable=True)
    size_bytes: Mapped[int | None] = mapped_column(Integer, nullable=True)
    sha256: Mapped[str | None] = mapped_column(String(64), nullable=True)
    # CASE-004: every authorized access is visible here + audit log.
    access_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)

    case: Mapped["SupportCase"] = relationship("SupportCase", back_populates="attachments")

    def __repr__(self) -> str:
        return f"<CaseAttachment id={self.id} case={self.case_id} file={self.filename!r}>"
